#!/usr/bin/env python3
"""Build lib/map/country_shapes_data.dart from Natural Earth country outlines.

Natural Earth is public domain, so the outlines ship inside the app with no
map service, API key or attribution requirement.

Encoding (decoded by lib/map/country_shapes.dart):
    repeated per country:
        2 bytes   ISO 3166-1 alpha-2 code (ASCII)
        varint    ring count
        repeated per ring:
            varint    point count
            repeated per point: zigzag varint dLon, zigzag varint dLat
                      in hundredths of a degree, delta from the previous
                      point (the first point is a delta from 0,0)
    The byte stream is base64 encoded into one Dart string constant.

Usage (from apps/g_vpn):
    pip install shapely
    python3 tool/build_country_shapes.py
"""

from __future__ import annotations

import base64
import json
import sys
import urllib.request
from collections import defaultdict
from pathlib import Path

from shapely.geometry import Polygon, shape

SOURCE_URL = (
    'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/'
    'master/geojson/ne_50m_admin_0_countries.geojson'
)
OUTPUT = Path(__file__).resolve().parent.parent / 'lib' / 'map' / 'country_shapes_data.dart'

# Simplification tolerance in degrees. 0.03 keeps coastlines readable at
# country zoom while holding the payload near 110 KB.
TOLERANCE = 0.03

# Quantisation: hundredths of a degree (about 1 km at the equator).
SCALE = 100

# Territories Natural Earth lists without an ISO code, folded into the
# country that surrounds them so the outline has no gap.
FOLD_INTO = {
    'Somaliland': 'SO',
    'Northern Cyprus': 'CY',
}


def zigzag(n: int) -> int:
    """Map signed to unsigned so small negatives stay small."""
    return (n << 1) ^ (n >> 63)


def put_varint(n: int, out: bytearray) -> None:
    """Append an unsigned LEB128 varint."""
    while True:
        byte = n & 0x7F
        n >>= 7
        if n:
            out.append(byte | 0x80)
        else:
            out.append(byte)
            return


def iso_code(props: dict) -> str | None:
    """Prefer the 'EH' code, which Natural Earth fills for France and Norway."""
    if props.get('ADMIN') in FOLD_INTO:
        return FOLD_INTO[props['ADMIN']]
    for key in ('ISO_A2_EH', 'ISO_A2'):
        code = props.get(key)
        if code and len(code) == 2 and code.isalpha():
            return code.upper()
    return None


def quantised_rings(geometry: dict) -> list[list[tuple[int, int]]]:
    """Simplify, keep exterior rings only, quantise and drop repeats."""
    simplified = shape(geometry).simplify(TOLERANCE, preserve_topology=True)
    polygons = [simplified] if isinstance(simplified, Polygon) else list(simplified.geoms)
    rings = []
    for polygon in polygons:
        if not isinstance(polygon, Polygon):
            continue
        points: list[tuple[int, int]] = []
        for lon, lat in polygon.exterior.coords[:-1]:
            point = (round(lon * SCALE), round(lat * SCALE))
            if not points or points[-1] != point:
                points.append(point)
        if len(points) >= 3:
            rings.append(points)
    return rings


def encode(countries: dict[str, list[list[tuple[int, int]]]]) -> bytes:
    out = bytearray()
    for code in sorted(countries):
        rings = countries[code]
        out += code.encode('ascii')
        put_varint(len(rings), out)
        for ring in rings:
            put_varint(len(ring), out)
            prev_x = prev_y = 0
            for x, y in ring:
                put_varint(zigzag(x - prev_x), out)
                put_varint(zigzag(y - prev_y), out)
                prev_x, prev_y = x, y
    return bytes(out)


def main() -> int:
    print(f'Downloading {SOURCE_URL}')
    with urllib.request.urlopen(SOURCE_URL, timeout=60) as response:
        features = json.load(response)['features']

    countries: dict[str, list] = defaultdict(list)
    skipped = []
    for feature in features:
        code = iso_code(feature['properties'])
        if code is None:
            skipped.append(feature['properties'].get('ADMIN', '?'))
            continue
        countries[code].extend(quantised_rings(feature['geometry']))

    payload = base64.b64encode(encode(countries)).decode('ascii')
    points = sum(len(r) for rings in countries.values() for r in rings)

    # Split the literal into 100-character lines so the file stays diffable.
    lines = [payload[i:i + 100] for i in range(0, len(payload), 100)]
    body = '\n'.join(f"    '{line}'" for line in lines)
    OUTPUT.write_text(
        '// GENERATED by tool/build_country_shapes.py. Do not edit by hand.\n'
        '//\n'
        '// Country outlines from Natural Earth 1:50m (public domain),\n'
        f'// simplified to {TOLERANCE} degrees and quantised to 1/{SCALE} degree.\n'
        f'// {len(countries)} countries, {points} points.\n'
        '\n'
        '/// Base64 payload decoded by `CountryShapes`.\n'
        'const String countryShapesData =\n'
        f'{body};\n',
        encoding='utf-8',
    )
    print(f'Wrote {OUTPUT} ({len(countries)} countries, {points} points, {len(payload)} chars)')
    if skipped:
        print('Skipped (no ISO code): ' + ', '.join(skipped))
    return 0


if __name__ == '__main__':
    sys.exit(main())
