import 'package:flutter/widgets.dart';

/// "Pocket OS", written out by hand: the second half of Pocket's boot.
///
/// ─── THE LETTERING IS BAKED, NOT A FONT ─────────────────────────────────────
///
/// The words are the outlines of Sacramento (Astigmatic, SIL Open Font Licence
/// 1.1; the licence allows outlines of the glyphs to be embedded in software),
/// a monoline script: one even hairline, joined lowercase, long entry strokes.
/// Converting the two words to a path once, offline, means no font file in the
/// APK, no download on first boot, and nothing for the per-pack font work to
/// wait on. It is not Apple's hello lettering, which is their artwork.
///
/// Regenerate with fontTools from the Fontsource woff2 if the words change:
/// draw each glyph through a TransformPen(1, 0, 0, -1, advance, 0) into a
/// RecordingPen and write the ops below. Font units, y down, baseline at 0.
///
/// ─── THE WRITING IS A REVEAL ────────────────────────────────────────────────
///
/// A monoline script's outline is a thin closed loop around each stroke, so
/// dashing it on would draw both sides of every stroke at once. What reads as
/// a pen is a soft-edged wipe that follows the line left to right, which is
/// how a connected script is actually written.
class HelloLettering extends StatelessWidget {
  const HelloLettering({
    super.key,
    required this.progress,
    required this.color,
    this.width = 280,
  });

  /// 0 shows nothing, 1 shows every letter.
  final Animation<double> progress;

  final Color color;

  /// How wide the written words are, in dp.
  final double width;

  @override
  Widget build(BuildContext context) {
    final bounds = _words.getBounds();
    final scale = width / bounds.width;
    return SizedBox(
      width: width,
      height: bounds.height * scale,
      child: CustomPaint(
        painter: _HelloPainter(
          progress: progress,
          color: color,
          scale: scale,
          bounds: bounds,
        ),
      ),
    );
  }
}

class _HelloPainter extends CustomPainter {
  _HelloPainter({
    required this.progress,
    required this.color,
    required this.scale,
    required this.bounds,
  }) : super(repaint: progress);

  final Animation<double> progress;
  final Color color;
  final double scale;
  final Rect bounds;

  /// How soft the pen's leading edge is, in font units: about a letter's
  /// stroke width at the size this draws, so the line fades in rather than
  /// being cut.
  static const _feather = 420.0;

  @override
  void paint(Canvas canvas, Size size) {
    final t = progress.value.clamp(0.0, 1.0);
    if (t == 0) return;

    canvas.save();
    canvas.scale(scale);
    canvas.translate(-bounds.left, -bounds.top);

    final layer = bounds.inflate(_feather);
    canvas.saveLayer(layer, Paint());
    canvas.drawPath(_words, Paint()..color = color);

    // The pen: opaque behind it, clear ahead of it, soft in between. Runs a
    // feather past the last letter so the final stroke lands fully drawn.
    final edge =
        bounds.left + (bounds.width + _feather * 2) * t - _feather;
    canvas.drawRect(
      layer,
      Paint()
        ..blendMode = BlendMode.dstIn
        ..shader = LinearGradient(
          colors: [color, color.withValues(alpha: 0)],
        ).createShader(
          Rect.fromLTRB(edge - _feather, 0, edge + 1, 1),
        ),
    );
    canvas.restore();
    canvas.restore();
  }

  @override
  bool shouldRepaint(_HelloPainter old) =>
      old.color != color || old.scale != scale;
}

/// The words as one path, built once.
final Path _words = _decode(_pocketOs);

Path _decode(List<int> ops) {
  final p = Path();
  var i = 0;
  double at(int k) => ops[i + k].toDouble();
  while (i < ops.length) {
    switch (ops[i++]) {
      case 0:
        p.moveTo(at(0), at(1));
        i += 2;
      case 1:
        p.lineTo(at(0), at(1));
        i += 2;
      case 2:
        p.quadraticBezierTo(at(0), at(1), at(2), at(3));
        i += 4;
      case 3:
        p.cubicTo(at(0), at(1), at(2), at(3), at(4), at(5));
        i += 6;
      default:
        p.close();
    }
  }
  return p;
}

